"""Writes deploy/k8s/base/network.yaml and mesh-ports.yaml from security/tests/network_paths.py.
Design: docs/network.md, docs/mtls.md

    python scripts/gen_network_policies.py        (tests/test_k8s_manifests.py checks both are current)

One table, three users: this file, ST4 (the running cluster) and the manifest tests. Each allowed
path opens two ports at both ends: the app's port, and Linkerd's inbound proxy port (4143),
because between two meshed pods the connection goes to the receiver's proxy, not the app port
(docs/mtls.md). Every pod may also reach DNS and the Linkerd control plane, and Prometheus may
read every proxy's metrics (4191).
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from security.tests.network_paths import HTTP_PORTS, LISTENS, PATHS, PUBLIC

OUT = ROOT / "deploy" / "k8s" / "base" / "network.yaml"
MESH_OUT = ROOT / "deploy" / "k8s" / "base" / "mesh-ports.yaml"
PROXY_INBOUND = 4143   # Linkerd's proxy: where meshed connections arrive
PROXY_ADMIN = 4191     # Linkerd's proxy: its metrics

HEADER = f"""# Network isolation (week 4, step 3; threat 4, test ST4). Design: docs/network.md
# GENERATED by scripts/gen_network_policies.py from security/tests/network_paths.py: edit the table
# and run the script, never this file (tests/test_k8s_manifests.py checks it is current).
#
# Default deny in both directions, then one policy per workload: who may call it (ingress) and
# whom it may call (egress). A path must be allowed at both ends, on the app's port and on
# Linkerd's proxy port {PROXY_INBOUND} (docs/mtls.md). kubectl port-forward and exec don't go through
# the pod network, so these rules don't affect the laptop tools.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: default-deny
spec:
  podSelector: {{}}   # every pod in the namespace, including one with no labels at all
  policyTypes: [Ingress, Egress]
---
# Every pod may look up names (CoreDNS) and reach the Linkerd control plane (its certificate,
# where to send traffic, which callers to accept). Nothing else by default.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: dns-and-mesh
spec:
  podSelector: {{}}
  policyTypes: [Egress]
  egress:
    - to:
        - namespaceSelector: {{matchLabels: {{kubernetes.io/metadata.name: kube-system}}}}
          podSelector: {{matchLabels: {{k8s-app: kube-dns}}}}
      ports:
        - {{protocol: UDP, port: 53}}
        - {{protocol: TCP, port: 53}}
    - to:
        - namespaceSelector: {{matchLabels: {{kubernetes.io/metadata.name: linkerd}}}}"""


def ports(*numbers):
    return "[" + ", ".join(f"{{protocol: TCP, port: {n}}}" for n in numbers) + "]"


def peer(app):
    return f"        - podSelector: {{matchLabels: {{app: {app}}}}}"


def policy(app):
    lines = ["---", "apiVersion: networking.k8s.io/v1", "kind: NetworkPolicy",
             "metadata:", f"  name: {app}", "spec:",
             f"  podSelector: {{matchLabels: {{app: {app}}}}}", "  policyTypes: [Ingress, Egress]"]
    ingress = []
    if app == "kong":
        ingress += ["    # The public entrance: anyone may reach the proxy port (NodePort 30080)",
                    f"    - ports: {ports(8000)}"]
    for src, dst, port, why in PATHS:
        if dst == app:
            ingress += [f"    - from:  # {why}", peer(src),
                        f"      ports: {ports(port, PROXY_INBOUND)}"]
    if app != "prometheus":
        ingress += ["    - from:  # its Linkerd proxy's metrics", peer("prometheus"),
                    f"      ports: {ports(PROXY_ADMIN)}"]
    lines += ["  ingress:"] + ingress

    egress = []
    for src, dst, port, why in PATHS:
        if src == app:
            egress += [f"    - to:  # {why}", peer(dst), f"      ports: {ports(port, PROXY_INBOUND)}"]
    if app == "prometheus":
        egress += ["    - to:  # every Linkerd proxy's metrics", "        - podSelector: {}",
                   f"      ports: {ports(PROXY_ADMIN)}",
                   "    # The Kubernetes API, for pod discovery and CPU numbers (cAdvisor through the API)",
                   "    - to:",
                   "        - ipBlock: {cidr: 10.43.0.1/32}     # its Service address",
                   "        - ipBlock: {cidr: 172.16.0.0/12}    # the k3d nodes (Docker network)",
                   f"      ports: {ports(443, 6443)}"]
    lines += ["  egress:"] + egress if egress else ["  egress: []   # may call nothing (DNS and mesh only, above)"]
    return "\n".join(lines)


def render():
    return HEADER + "\n" + "\n".join(policy(app) for app in LISTENS) + "\n"


MESH_HEADER = """# Per-port callers, checked by identity (week 4, step 4; docs/mtls.md).
# GENERATED by scripts/gen_network_policies.py from security/tests/network_paths.py.
#
# Between meshed pods every connection arrives on the proxy port 4143, whatever app port it is
# for, so a NetworkPolicy can say which pods may talk but not on which port. For a pod with
# several ports and different callers on each, the mesh decides instead: one Server per port,
# and an AuthorizationPolicy naming exactly the service accounts the table allows. Kong's public
# port is in mesh.yaml."""


def mesh_ports():
    docs = [MESH_HEADER]
    for app, listens in LISTENS.items():
        if len(listens) < 2:
            continue   # one port: the NetworkPolicy already says who may reach it
        for port in listens:
            if (app, port) in PUBLIC:
                continue
            callers = sorted({src for src, dst, p, _ in PATHS if (dst, p) == (app, port)})
            name = f"{app}-{port}"
            protocol = "HTTP/1" if port in HTTP_PORTS else "opaque"
            refs = "\n".join(f"    - {{kind: ServiceAccount, name: {c}}}" for c in callers)
            # Several callers can't be listed on the policy itself (Linkerd's validator allows
            # one ServiceAccount there), so they go in a MeshTLSAuthentication it refers to
            docs.append(f"""apiVersion: policy.linkerd.io/v1beta3
kind: Server
metadata:
  name: {name}
spec:
  podSelector:
    matchLabels: {{app: {app}}}
  port: {port}
  proxyProtocol: {protocol}
  accessPolicy: deny   # only the callers below
---
apiVersion: policy.linkerd.io/v1alpha1
kind: MeshTLSAuthentication
metadata:
  name: {name}-callers
spec:
  identityRefs:   # {", ".join(callers)}
{refs}
---
apiVersion: policy.linkerd.io/v1alpha1
kind: AuthorizationPolicy
metadata:
  name: {name}
spec:
  targetRef: {{group: policy.linkerd.io, kind: Server, name: {name}}}
  requiredAuthenticationRefs:
    - {{group: policy.linkerd.io, kind: MeshTLSAuthentication, name: {name}-callers}}""")
    return docs[0] + "\n" + "\n---\n".join(docs[1:]) + "\n"


if __name__ == "__main__":
    OUT.write_text(render())
    MESH_OUT.write_text(mesh_ports())
    print(f"wrote {OUT.relative_to(ROOT)} and {MESH_OUT.relative_to(ROOT)}: "
          f"{len(PATHS)} paths, {len(LISTENS)} workloads")
